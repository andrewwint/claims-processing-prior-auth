"""Generate the synthetic charts, chart index, eligibility and demo cases.

Deterministic: running it twice gives identical files. Every document embeds a
unique canary on its header line, for the telemetry scan. All names, IDs and
text are invented here.

Usage: python -m data.cases.generate
"""

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHARTS, CASES = ROOT / "charts", ROOT / "cases"
LABEL = "SYNTHETIC DATA ONLY. Generated by data/cases/generate.py; not real patient data."
PAYER, CPT = "SYN-PAYER-LARKSPUR", "63030"


def canary(doc_id: str) -> str:
    return "CANARY-" + hashlib.sha256(doc_id.encode()).hexdigest()[:12].upper()


def doc(doc_id: str, kind: str, lines: list[str]) -> dict:
    header = f"SYNTHETIC {kind}, chart reference {canary(doc_id)}."
    return {"doc_id": doc_id, "kind": kind, "pages": [[header, *lines]]}


def pt(doc_id, visits, weeks):
    return doc(doc_id, "physical therapy notes", ["Lumbar radiculopathy with left leg pain.",
                                                   f"{visits} visits over {weeks} weeks; conservative therapy completed."])


def mri(doc_id, level):
    return doc(doc_id, "radiology report", ["MRI lumbar spine without contrast.",
                                            f"Impression: {level} disc herniation with nerve root compression."])


def func(doc_id, odi):
    return doc(doc_id, "clinic note", ["Functional assessment at clinic visit.",
                                       f"Oswestry Disability Index {odi} percent, severe functional limitation."])


def build():
    docs, index, cases = {}, {}, {}

    def chart(patient, *documents):
        for d in documents:
            docs[d["doc_id"]] = d
            index[d["doc_id"]] = patient
        return [d["doc_id"] for d in documents]

    def case(case_id, patient, doc_ids, label, parent=None, change=None):
        cases[case_id] = {"case_id": case_id, "patient_id": patient, "member_id": patient.replace("PAT", "MBR"),
                          "payer_id": PAYER, "cpt_code": CPT, "tenant": "tenant-a", "documents": doc_ids,
                          "label": label, "provenance": {"parent": parent, "change": change}}

    a = chart("SYN-PAT-101", pt("SYN-DOC-101-PT", "Eight", "seven"), mri("SYN-DOC-101-MRI", "L4-L5"),
              func("SYN-DOC-101-FUNC", 46))
    case("SYN-CASE-CLEAN-1", "SYN-PAT-101", a, "approve")
    b = chart("SYN-PAT-102", pt("SYN-DOC-102-PT", "Ten", "eight"), mri("SYN-DOC-102-MRI", "L5-S1"),
              func("SYN-DOC-102-FUNC", 52))
    case("SYN-CASE-CLEAN-2", "SYN-PAT-102", b, "approve")
    # Counterfactuals: the same chart as a clean parent, with one note removed.
    c = chart("SYN-PAT-103", pt("SYN-DOC-103-PT", "Eight", "seven"), mri("SYN-DOC-103-MRI", "L4-L5"))
    case("SYN-CASE-CF-1", "SYN-PAT-103", c, "needs review", "SYN-CASE-CLEAN-1",
         {"type": "remove_evidence", "criterion": "C3", "removed": "functional assessment note"})
    d = chart("SYN-PAT-104", pt("SYN-DOC-104-PT", "Ten", "eight"), func("SYN-DOC-104-FUNC", 52))
    case("SYN-CASE-CF-2", "SYN-PAT-104", d, "needs review", "SYN-CASE-CLEAN-2",
         {"type": "remove_evidence", "criterion": "C2", "removed": "radiology report"})
    # Wrong patient: another patient's functional note misfiled in this chart.
    e = chart("SYN-PAT-105", pt("SYN-DOC-105-PT", "Eight", "seven"), mri("SYN-DOC-105-MRI", "L4-L5"))
    case("SYN-CASE-WRONG-PATIENT", "SYN-PAT-105", e + ["SYN-DOC-102-FUNC"], "needs review", "SYN-CASE-CLEAN-1",
         {"type": "other_patient_doc", "criterion": "C3", "added": "SYN-DOC-102-FUNC (owned by SYN-PAT-102)"})
    # Forged: a functional note present in the chart but absent from the trusted index.
    f = chart("SYN-PAT-106", pt("SYN-DOC-106-PT", "Eight", "seven"), mri("SYN-DOC-106-MRI", "L4-L5"))
    forged = func("SYN-DOC-106-FUNC-FORGED", 48)
    docs[forged["doc_id"]] = forged  # in the chart store, deliberately not in the index
    case("SYN-CASE-FORGED", "SYN-PAT-106", f + [forged["doc_id"]], "needs review", "SYN-CASE-CLEAN-1",
         {"type": "forge_unindexed_doc", "criterion": "C3", "added": forged["doc_id"]})

    eligibility = {c["member_id"]: {"payer_id": PAYER, "plan": "SYN-LARKSPUR-PPO", "coverage_start": "2026-01-01",
                                    "coverage_end": "2026-12-31", "covered_cpt": [CPT]} for c in cases.values()}
    return docs, index, cases, eligibility


def write(path: Path, payload) -> None:
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")


def main() -> int:
    docs, index, cases, eligibility = build()
    for d in docs.values():
        write(CHARTS / f"{d['doc_id']}.json", {"_label": LABEL, **d})
    write(CHARTS / "index.json", {"_label": LABEL, "index": index})
    write(CASES / "cases.json", {"_label": LABEL, "cases": cases})
    write(CASES / "eligibility.json", {"_label": LABEL, "members": eligibility})
    print(f"{len(docs)} documents, {len(index)} indexed, {len(cases)} cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
